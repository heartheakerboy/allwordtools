/** Resolve an array of slugs to Tool objects, preserving order. */
export function toolsFromSlugs(slugs: string[]): Tool[] {
  return slugs
    .map((slug) => allTools.find((t) => t.slug === slug))
    .filter((t): t is Tool => Boolean(t));
}

