function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function generateOne(type: NameType): string {
  switch (type) {
    case "dog":
      return pickOne(DOG_NAMES);
    case "cat":
      return pickOne(CAT_NAMES);
    case "team":
      return `${pickOne(TEAM_ADJ)} ${pickOne(TEAM_NOUNS)}`;
    case "guild":
      return Math.random() < 0.5
        ? `${pickOne(GUILD_ROLES)} of ${pickOne(GUILD_THEMES)}`
        : `The ${pickOne(ADJECTIVES)} ${pickOne(CREATURES)}`;
    case "clan":
      return Math.random() < 0.5
        ? `Clan ${capitalize(pickOne(CLAN_PREFIX))}${pickOne(CLAN_SUFFIX)}`
        : `${capitalize(pickOne(CLAN_PREFIX))}${pickOne(CLAN_SUFFIX)}`;
    case "character":
      return `${pickOne(CHAR_FIRST)} ${pickOne(CHAR_LAST)}`;
    case "demon": {
      const base = `${pickOne(DEMON_START)}${Math.random() < 0.5 ? pickOne(DEMON_MID) : ""}${pickOne(DEMON_END)}`;
      return Math.random() < 0.4 ? `${base} ${pickOne(DEMON_TITLES)}` : base;
    }
    case "alien":
      return `${pickOne(ALIEN_START)}${Math.random() < 0.6 ? pickOne(ALIEN_MID) : ""}${pickOne(ALIEN_END)}`;
    case "witch": {
      const full = `${pickOne(WITCH_FIRST)} ${pickOne(WITCH_LAST)}`;
      return Math.random() < 0.4 ? `${pickOne(WITCH_FIRST)} ${pickOne(WITCH_EPITHET)}` : full;
    }
    case "knight":
      return Math.random() < 0.5
        ? `Sir ${pickOne(KNIGHT_FIRST)} ${pickOne(KNIGHT_EPITHET)}`
        : `Sir ${pickOne(KNIGHT_FIRST)} of ${pickOne(KNIGHT_PLACE)}`;
    case "vampire":
      return Math.random() < 0.45
        ? `${pickOne(VAMPIRE_FIRST)} ${pickOne(VAMPIRE_LAST)}`
        : `${pickOne(VAMPIRE_FIRST)} ${pickOne(VAMPIRE_LAST)}, ${pickOne(VAMPIRE_TITLE)}`;
    case "robot": {
      const roll = Math.random();
      if (roll < 0.4)
        return `${pickOne(ROBOT_PREFIX)}-${Math.floor(Math.random() * 90) + 10} ${pickOne(ROBOT_CORE)}`;
      if (roll < 0.75) return `${pickOne(ROBOT_CORE)} ${pickOne(ROBOT_SUFFIX)}`;
      return `${pickOne(ROBOT_PREFIX)}${pickOne(ROBOT_CORE)}`;
    }
  }
}

export function generateNames(type: NameType, count: number): string[] {
  const n = Math.max(1, Math.min(50, count));
  // Pet names come from curated lists — draw unique picks when possible.
  if (type === "dog" || type === "cat") {
    const pool = type === "dog" ? DOG_NAMES : CAT_NAMES;
    return pickMany([...new Set(pool)], Math.min(n, new Set(pool).size));
  }
  // Generative names — dedupe within a batch.
  const out = new Set<string>();
  let guard = 0;
  while (out.size < n && guard < n * 40) {
    out.add(generateOne(type));
    guard++;
  }
  return shuffle([...out]);
}
